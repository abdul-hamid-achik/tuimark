// Stale generated files: anything under the generated directories this run
// did not produce.
const owned = ['snippets/out', 'public/shots']
const stray = []
for (const dir of owned) {
  const abs = join(DOCS, dir)
  if (!existsSync(abs)) continue
  for (const f of readdirSync(abs)) {
    const p = `${dir}/${f}`
    if (!files.has(p)) stray.push(p)
  }
}

if (CHECK) {
  const stale = []
  for (const [path, content] of files) {
    const abs = join(DOCS, path)
    if (!existsSync(abs) || readFileSync(abs, 'utf8') !== content) stale.push(path)
  }
  stale.push(...stray.map((p) => `${p} (not generated any more)`))
  if (stale.length) {
    console.error(`generate --check: ${stale.length} generated file(s) are stale; run \`task docs-gen\`:`)
    for (const p of stale) console.error(`  docs/${p}`)
    process.exit(1)
  }
  console.log(`generate --check: ${files.size} generated files are up to date`)
} else {
  for (const [path, content] of files) {
    const abs = join(DOCS, path)
    mkdirSync(dirname(abs), { recursive: true })
    const old = existsSync(abs) ? readFileSync(abs, 'utf8') : null
    if (old !== content) writeFileSync(abs, content)
  }
  if (stray.length) console.warn(`generate: not generated any more (delete them): ${stray.map((p) => `docs/${p}`).join(', ')}`)
  console.log(`generate: ${files.size} files up to date`)
}
