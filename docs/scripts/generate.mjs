// Regenerates every part of the docs site that comes from the tuimark CLI,
// so the site cannot drift from the runtime it documents:
//
//   content/reference/{cli,tags,css,keys,diagnostics}.mdx   from `tuimark --help` and `tuimark agents`
//   snippets/out/*                       the command output the guide pages show
//   public/shots/*.svg                   screenshots rendered from `tuimark play`, and animated
//                                        demos from the examples' own -demo and from scripted
//                                        `tuimark play --frames` sessions (the landing page's hero)
//   lib/generated/{catalog,shots}.json   counts, tag lists and the shot index the site's
//                                        components read
//   lib/generated/kit.json               the kit's component documents and templates, for /kit
//
// Usage, from the repository root (or `task docs-gen` / `task docs-check`):
//
//   go build -o bin/tuimark ./cmd/tuimark
//   node docs/scripts/generate.mjs            # rewrite the generated files
//   node docs/scripts/generate.mjs --check    # exit 1 when any of them is stale
//
// TUIMARK=/path/to/tuimark overrides the binary (default: bin/tuimark).
// Every command runs with a fixed environment, and dump/play/validate never
// read TUIMARK_* variables, so the output is the same on every machine.

