const agents = tuimark(['agents']).out

/** The body of one `### heading` section of `tuimark agents`. */
function section(heading) {
  const lines = agents.split('\n')
  const start = lines.findIndex((l) => l.trim() === heading)
  if (start < 0) throw new Error(`generate: \`tuimark agents\` has no "${heading}" section`)
  let end = lines.findIndex((l, i) => i > start && /^#{1,3} /.test(l))
  if (end < 0) end = lines.length
  return lines.slice(start + 1, end).join('\n').trim()
}

/** Split a section into paragraphs and bullet blocks. */
function blocks(text) {
  const out = []
  for (const chunk of text.split(/\n\s*\n/)) {
    const lines = chunk.split('\n').filter((l) => l.trim() !== '')
    if (lines.length === 0) continue
    if (lines.every((l) => l.startsWith('- '))) out.push({ kind: 'list', lines })
    else out.push({ kind: 'para', text: lines.join(' ') })
  }
  return out
}

const cell = (s) => s.replace(/\|/g, '\\|')
const codeList = (items) => items.map((a) => `\`${a}\``).join(' ')

const catalog = { tags: [], tagsV2: [], tagsCurrent: [], properties: 0, diagnostics: 0 }

function tagsPage() {
  const parts = blocks(section('### Attributes per tag'))
  const body = []
  let tables = 0
  let v2Heading = false
  let v3Heading = false
  let currentHeading = false
  for (const b of parts) {
    if (b.kind === 'para') {
      if (b.text.startsWith('Only in a `<tui version="2">` document')) {
        body.push('## Added by `version="2"`', '')
        v2Heading = true
      }
      if (b.text.startsWith('Only in a `<tui version="3">` document')) {
        body.push('## Added by `version="3"`', '')
        v3Heading = true
      }
      if (b.text.startsWith('Only in a `<tui>` without `version`')) {
        body.push('## Added by the current language', '')
        currentHeading = true
      }
      body.push(mdx(b.text), '')
      continue
    }
    const rows = []
    const rest = []
    for (const line of b.lines) {
      const m = /^- `([a-z]+)`: (.+)$/.exec(line)
      if (!m) {
        rest.push(line)
        continue
      }
      const attrs = m[2] === '(no attributes)' ? '—' : codeList(m[2].split(', '))
      if (tables === 0) catalog.tags.push(m[1])
      else if (tables === 1 && !catalog.tags.includes(m[1])) catalog.tagsV2.push(m[1])
      else if (tables === 3 && !catalog.tags.includes(m[1]) && !catalog.tagsV2.includes(m[1])) catalog.tagsCurrent.push(m[1])
      rows.push(`| \`<${m[1]}>\` | ${cell(attrs)} |`)
    }
    if (rows.length) {
      tables++
      if (tables === 1) body.push('## Every version', '')
      else if (tables === 2 && !v2Heading) throw new Error('generate: the version="2" attribute table has no introduction')
      else if (tables === 3 && !v3Heading) throw new Error('generate: the version="3" attribute table has no introduction')
      else if (tables === 4 && !currentHeading) throw new Error('generate: the current-language attribute table has no introduction')
      body.push('| Tag | Attributes |', '|---|---|', ...rows, '')
    }
    if (rest.length) body.push(...rest.map(mdx), '')
  }
  if (tables !== 4) throw new Error(`generate: expected 4 attribute tables in "Attributes per tag", found ${tables}`)
  emit(
    'content/reference/tags.mdx',
    [
      '---',
      'title: Tags and attributes',
      'description: Every Tuimark tag and the exact attributes it accepts, and what a document that pins an older version leaves out.',
      'editLink: false',
      '---',
      '',
      GENERATED('`tuimark agents`'),
      '',
      'The vocabulary is closed: a tag outside this page is `V001`, and an attribute a tag does not list is `V002`. This page is generated from the same catalog the runtime validates against. A `<tui>` without `version` is the current language and accepts every tag and attribute below. The sections after the first mark what a document that pins `version="1"`, `"2"`, or `"3"` leaves out, and the last one what only the current language accepts: `checkbox`, `select`, `include`, `fragment`, `template`, `use`, `single`, and `indeterminate`. See [The .tui language](/guide/language) for what each tag does.',
      '',
      ...body,
    ].join('\n'),
  )
}

function cssPage() {
  const lines = section('### CSS properties').split('\n').filter((l) => l.trim())
  const rows = lines.map((line) => {
    const m = /^- `([a-z-]+)`: (.+)$/.exec(line)
    if (!m) throw new Error(`generate: unexpected CSS property line: ${line}`)
    let [, prop, values] = m
    let note = ''
    const paren = /\s*\(([^()]*)\)$/.exec(values)
    if (paren) {
      values = values.slice(0, paren.index)
      if (paren[1] === 'version="2" stylesheets only') note = 'not in `version="1"`'
      else if (paren[1] === 'version="3" stylesheets only') note = 'not in `version="1"` or `"2"`'
      else if (paren[1] === 'version="2"') {
        const alts = values.split(' | ')
        note = `\`${alts[alts.length - 1]}\`: not in \`version="1"\``
      } else if (paren[1] === 'version="3"' && prop === 'wrap') {
        note = '`truncate-start`, `truncate-middle`: not in `version="1"` or `"2"`'
      } else note = paren[1]
    }
    const alts = values.split(' | ')
    const simple = alts.length > 1 && alts.every((a) => /^[\w$#%().\-]+$/.test(a))
    const shown = simple ? alts.map((a) => `\`${a}\``).join(' · ') : cell(values.replace(/\b(N|N%|Nfr)\b/g, '$1'))
    return `| \`${prop}\` | ${mdx(shown)} | ${mdx(cell(note))} |`
  })
  if (rows.length < 30) throw new Error(`generate: only ${rows.length} CSS properties parsed`)
  catalog.properties = rows.length
  emit(
    'content/reference/css.mdx',
    [
      '---',
      'title: CSS properties',
      'description: Every TCSS property Tuimark accepts and the values it takes.',
      'editLink: false',
      '---',
      '',
      GENERATED('`tuimark agents`'),
      '',
      'Every property TCSS accepts. An unknown property, or a value outside its list, is `V003`. A document without `version` accepts all of them; the notes say what an older `version="1"` or `version="2"` document leaves out. Sizes are `N` cells, `N%` of the parent, `Nfr` shares of what is left, or `auto`. Colors are a `$token` (or `var(--token)`), one of the 16 ANSI names, `#rgb`, `#rrggbb`, or `default`. See [TCSS](/guide/tcss) and [Layout](/guide/layout) for how they combine.',
      '',
      '| Property | Values | Notes |',
      '|---|---|---|',
      ...rows,
      '',
    ].join('\n'),
  )
}

function keysPage() {
  const parts = blocks(section('### Key tokens'))
  const named = parts.find((b) => b.kind === 'para' && b.text.startsWith('Named: '))
  if (!named) throw new Error('generate: "Key tokens" has no "Named:" line')
  const tokens = named.text.slice('Named: '.length).split(', ')
  const others = parts.filter((b) => b !== named).map((b) => (b.kind === 'para' ? b.text : b.lines.join('\n')))
  emit(
    'content/reference/keys.mdx',
    [
      '---',
      'title: Key tokens',
      'description: The key names a Tuimark keymap accepts in keys="…".',
      'editLink: false',
      '---',
      '',
      GENERATED('`tuimark agents`'),
      '',
      'A `<bind keys="…">` row takes one or more of these tokens, separated by commas: `keys="q,ctrl+c"`. The same names are the steps of `tuimark play --input`. See [Keymap, actions and focus](/guide/interaction).',
      '',
      '## Named keys',
      '',
      '| Token | Key |',
      '|---|---|',
      ...tokens.map((t) => `| \`${t}\` | ${keyName(t)} |`),
      '',
      '## Other tokens',
      '',
      ...others.flatMap((t) => [mdx(t), '']),
    ].join('\n'),
  )
}

function keyName(t) {
  const names = {
    enter: 'Enter / Return', esc: 'Escape', tab: 'Tab', backspace: 'Backspace', space: 'Space bar',
    up: 'Arrow up', down: 'Arrow down', left: 'Arrow left', right: 'Arrow right', home: 'Home', end: 'End',
    pgup: 'Page up', pgdn: 'Page down', 'shift+tab': 'Shift + Tab',
    delete: 'Delete (forward delete)', 'shift+enter': 'Shift + Enter', 'ctrl+enter': 'Ctrl + Enter',
    'alt+enter': 'Alt + Enter', 'alt+backspace': 'Alt + Backspace',
  }
  for (let i = 1; i <= 12; i++) names[`f${i}`] = `Function key F${i}`
  if (!(t in names)) throw new Error(`generate: no description for key token "${t}"`)
  return names[t]
}

function diagnosticsPage() {
  const lines = section('### Diagnostic codes').split('\n').filter((l) => l.startsWith('| ') && !l.startsWith('| Code') )
  const rows = lines.map((l) => {
    const m = /^\| ([VLB]\d{3}) \| (\w+) \| (.*) \|$/.exec(l)
    if (!m) throw new Error(`generate: unexpected diagnostic row: ${l}`)
    return { code: m[1], pass: m[2], when: m[3] }
  })
  if (rows.length < 30) throw new Error(`generate: only ${rows.length} diagnostic codes parsed`)
  catalog.diagnostics = rows.length
  const groups = [
    ['V', 'Parse (`V…`) [#parse]', 'Reported while reading the `.tui` document and its stylesheets. Most are errors: the dump is not `ok`.'],
    ['L', 'Layout (`L…`) [#layout]', 'Reported while laying out a frame, so they depend on the size you render at.'],
    ['B', 'Bind (`B…`) [#bind]', 'Reported while resolving paths against the JSON data. `validate` checks them only when you pass `--data`.'],
  ]
  const body = []
  for (const [prefix, title, intro] of groups) {
    const g = rows.filter((r) => r.code.startsWith(prefix)).sort((a, b) => a.code.localeCompare(b.code))
    body.push(`## ${title}`, '', intro, '', '| Code | When |', '|---|---|')
    for (const r of g) body.push(`| <span id="${r.code.toLowerCase()}"></span>\`${r.code}\` | ${mdx(r.when)} |`)
    body.push('')
  }
  emit(
    'content/reference/diagnostics.mdx',
    [
      '---',
      'title: Diagnostic codes',
      'description: Every diagnostic code Tuimark reports, grouped by the pass that finds it.',
      'editLink: false',
      '---',
      '',
      GENERATED('`tuimark agents`'),
      '',
      'Every problem Tuimark finds is a diagnostic with a stable code. The letter names the pass (`V` parse, `L` layout, `B` bind), and the dump lists each one under `errors` with its `severity`, `code`, message, and source position. A dump with any error-severity diagnostic has `"ok": false`, and the CLI exits 2. Link to a code with its anchor, like [`/reference/diagnostics#v003`](#v003).',
      '',
      ...body,
    ].join('\n'),
  )
}

