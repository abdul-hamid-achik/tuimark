#!/usr/bin/env node
// Regenerates every part of the docs site that comes from the tuimark CLI,
// so the site cannot drift from the runtime it documents:
//
//   reference/{cli,tags,css,keys,diagnostics}.md   from `tuimark --help` and `tuimark agents`
//   snippets/out/*                                  the command output the guide pages show
//   public/shots/*.svg                              screenshots rendered from `tuimark play`
//
// Usage, from the repository root (or `task docs-gen` / `task docs-check`):
//
//   go build -o bin/tuimark ./cmd/tuimark
//   node docs/scripts/generate.mjs            # rewrite the generated files
//   node docs/scripts/generate.mjs --check    # exit 1 when any of them is stale
//
// TUIMARK=/path/to/tuimark overrides the binary (default: bin/tuimark).
// Every command runs with a fixed environment, and dump/play/validate never
// read TUIMARK_* variables, so the output is the same on every machine.

import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { renderSVG } from './svg.mjs'

const DOCS = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const REPO = resolve(DOCS, '..')
const SNIPPETS = join(DOCS, 'snippets')
const TUIMARK = process.env.TUIMARK ? resolve(process.env.TUIMARK) : join(REPO, 'bin', 'tuimark')
const CHECK = process.argv.includes('--check')

if (!existsSync(TUIMARK)) {
  console.error(`generate: ${relative(REPO, TUIMARK)} not found; build it first: go build -o bin/tuimark ./cmd/tuimark`)
  process.exit(1)
}

/** Every file this script owns, path (relative to docs/) → content. */
const files = new Map()
const emit = (path, content) => {
  if (files.has(path)) throw new Error(`generate: ${path} written twice`)
  files.set(path, content.endsWith('\n') ? content : content + '\n')
}

function tuimark(args, { cwd = REPO, exit = [0] } = {}) {
  const r = spawnSync(TUIMARK, args, {
    cwd,
    encoding: 'utf8',
    maxBuffer: 64 << 20,
    env: { PATH: process.env.PATH ?? '', HOME: process.env.HOME ?? '', LANG: 'en_US.UTF-8' },
  })
  if (r.error) throw r.error
  if (!exit.includes(r.status)) {
    throw new Error(`generate: tuimark ${args.join(' ')} (in ${relative(REPO, cwd) || '.'}) exited ${r.status}, want ${exit.join(' or ')}\n${r.stderr}${r.stdout.slice(0, 2000)}`)
  }
  return { out: r.stdout, err: r.stderr, status: r.status }
}

const GENERATED = (source) =>
  `<!-- Generated by docs/scripts/generate.mjs from ${source}. Do not edit by hand: run \`task docs-gen\`. -->`

// ── Reference pages ────────────────────────────────────────────────────────

const agents = tuimark(['agents']).out

/** The body of one `### heading` section of `tuimark agents`. */
function section(heading) {
  const lines = agents.split('\n')
  const start = lines.findIndex((l) => l.trim() === heading)
  if (start < 0) throw new Error(`generate: \`tuimark agents\` has no "${heading}" section`)
  let end = lines.findIndex((l, i) => i > start && /^#{1,3} /.test(l))
  if (end < 0) end = lines.length
  return lines.slice(start + 1, end).join('\n').trim()
}

/** Split a section into paragraphs and bullet blocks. */
function blocks(text) {
  const out = []
  for (const chunk of text.split(/\n\s*\n/)) {
    const lines = chunk.split('\n').filter((l) => l.trim() !== '')
    if (lines.length === 0) continue
    if (lines.every((l) => l.startsWith('- '))) out.push({ kind: 'list', lines })
    else out.push({ kind: 'para', text: lines.join(' ') })
  }
  return out
}

const cell = (s) => s.replace(/\|/g, '\\|')
const codeList = (items) => items.map((a) => `\`${a}\``).join(' ')

const catalog = { tags: [], tagsV2: [], properties: 0, diagnostics: 0 }

function tagsPage() {
  const parts = blocks(section('### Attributes per tag'))
  const body = []
  let tables = 0
  let v2Heading = false
  for (const b of parts) {
    if (b.kind === 'para') {
      if (b.text.startsWith('Only in a `<tui version="2">` document')) {
        body.push('## Added by `version="2"`', '')
        v2Heading = true
      }
      body.push(b.text, '')
      continue
    }
    const rows = []
    const rest = []
    for (const line of b.lines) {
      const m = /^- `([a-z]+)`: (.+)$/.exec(line)
      if (!m) {
        rest.push(line)
        continue
      }
      const attrs = m[2] === '(no attributes)' ? '—' : codeList(m[2].split(', '))
      if (tables === 0) catalog.tags.push(m[1])
      else if (!catalog.tags.includes(m[1])) catalog.tagsV2.push(m[1])
      rows.push(`| \`<${m[1]}>\` | ${cell(attrs)} |`)
    }
    if (rows.length) {
      tables++
      if (tables === 1) body.push('## Every document', '')
      else if (!v2Heading) throw new Error('generate: the version="2" attribute table has no introduction')
      body.push('| Tag | Attributes |', '|---|---|', ...rows, '')
    }
    if (rest.length) body.push(...rest, '')
  }
  if (tables !== 2) throw new Error(`generate: expected 2 attribute tables in "Attributes per tag", found ${tables}`)
  emit(
    'reference/tags.md',
    [
      '---',
      'title: Tags and attributes',
      'description: Every Tuimark tag and the exact attributes it accepts, in version="1" and version="2" documents.',
      'editLink: false',
      '---',
      '',
      GENERATED('`tuimark agents`'),
      '',
      '# Tags and attributes',
      '',
      'The vocabulary is closed: a tag outside this page is `V001`, and an attribute a tag does not list is `V002`. This page is generated from the same catalog the runtime validates against. See [The .tui language](/guide/language) for what each tag does.',
      '',
      ...body,
    ].join('\n'),
  )
}

function cssPage() {
  const lines = section('### CSS properties').split('\n').filter((l) => l.trim())
  const rows = lines.map((line) => {
    const m = /^- `([a-z-]+)`: (.+)$/.exec(line)
    if (!m) throw new Error(`generate: unexpected CSS property line: ${line}`)
    let [, prop, values] = m
    let note = ''
    const paren = /\s*\(([^()]*)\)$/.exec(values)
    if (paren) {
      values = values.slice(0, paren.index)
      if (paren[1] === 'version="2" stylesheets only') note = '`version="2"` only'
      else if (paren[1] === 'version="2"') {
        const alts = values.split(' | ')
        note = `\`${alts[alts.length - 1]}\` needs \`version="2"\``
      } else note = paren[1]
    }
    const alts = values.split(' | ')
    const simple = alts.length > 1 && alts.every((a) => /^[\w$#%().\-]+$/.test(a))
    const shown = simple ? alts.map((a) => `\`${a}\``).join(' · ') : cell(values.replace(/\b(N|N%|Nfr)\b/g, '$1'))
    return `| \`${prop}\` | ${shown} | ${cell(note)} |`
  })
  if (rows.length < 30) throw new Error(`generate: only ${rows.length} CSS properties parsed`)
  catalog.properties = rows.length
  emit(
    'reference/css.md',
    [
      '---',
      'title: CSS properties',
      'description: Every TCSS property Tuimark accepts and the values it takes.',
      'editLink: false',
      '---',
      '',
      GENERATED('`tuimark agents`'),
      '',
      '# CSS properties',
      '',
      'Every property TCSS accepts. An unknown property, or a value outside its list, is `V003`. Sizes are `N` cells, `N%` of the parent, `Nfr` shares of what is left, or `auto`. Colors are a `$token` (or `var(--token)`), one of the 16 ANSI names, `#rgb`, `#rrggbb`, or `default`. See [TCSS](/guide/tcss) and [Layout](/guide/layout) for how they combine.',
      '',
      '| Property | Values | Notes |',
      '|---|---|---|',
      ...rows,
      '',
    ].join('\n'),
  )
}

function keysPage() {
  const parts = blocks(section('### Key tokens'))
  const named = parts.find((b) => b.kind === 'para' && b.text.startsWith('Named: '))
  if (!named) throw new Error('generate: "Key tokens" has no "Named:" line')
  const tokens = named.text.slice('Named: '.length).split(', ')
  const others = parts.filter((b) => b !== named).map((b) => (b.kind === 'para' ? b.text : b.lines.join('\n')))
  emit(
    'reference/keys.md',
    [
      '---',
      'title: Key tokens',
      'description: The key names a Tuimark keymap accepts in keys="…".',
      'editLink: false',
      '---',
      '',
      GENERATED('`tuimark agents`'),
      '',
      '# Key tokens',
      '',
      'A `<bind keys="…">` row takes one or more of these tokens, separated by commas: `keys="q,ctrl+c"`. The same names are the steps of `tuimark play --input`. See [Keymap, actions and focus](/guide/interaction).',
      '',
      '## Named keys',
      '',
      '| Token | Key |',
      '|---|---|',
      ...tokens.map((t) => `| \`${t}\` | ${keyName(t)} |`),
      '',
      '## Other tokens',
      '',
      ...others.flatMap((t) => [t, '']),
    ].join('\n'),
  )
}

function keyName(t) {
  const names = {
    enter: 'Enter / Return', esc: 'Escape', tab: 'Tab', backspace: 'Backspace', space: 'Space bar',
    up: 'Arrow up', down: 'Arrow down', left: 'Arrow left', right: 'Arrow right', home: 'Home', end: 'End',
    pgup: 'Page up', pgdn: 'Page down', 'shift+tab': 'Shift + Tab',
  }
  if (!(t in names)) throw new Error(`generate: no description for key token "${t}"`)
  return names[t]
}

function diagnosticsPage() {
  const lines = section('### Diagnostic codes').split('\n').filter((l) => l.startsWith('| ') && !l.startsWith('| Code') )
  const rows = lines.map((l) => {
    const m = /^\| ([VLB]\d{3}) \| (\w+) \| (.*) \|$/.exec(l)
    if (!m) throw new Error(`generate: unexpected diagnostic row: ${l}`)
    return { code: m[1], pass: m[2], when: m[3] }
  })
  if (rows.length < 30) throw new Error(`generate: only ${rows.length} diagnostic codes parsed`)
  catalog.diagnostics = rows.length
  const groups = [
    ['V', 'Parse (`V…`) {#parse}', 'Reported while reading the `.tui` document and its stylesheets. Most are errors: the dump is not `ok`.'],
    ['L', 'Layout (`L…`) {#layout}', 'Reported while laying out a frame, so they depend on the size you render at.'],
    ['B', 'Bind (`B…`) {#bind}', 'Reported while resolving paths against the JSON data. `validate` checks them only when you pass `--data`.'],
  ]
  const body = []
  for (const [prefix, title, intro] of groups) {
    const g = rows.filter((r) => r.code.startsWith(prefix)).sort((a, b) => a.code.localeCompare(b.code))
    body.push(`## ${title}`, '', intro, '', '| Code | When |', '|---|---|')
    for (const r of g) body.push(`| <span id="${r.code.toLowerCase()}"></span>\`${r.code}\` | ${r.when} |`)
    body.push('')
  }
  emit(
    'reference/diagnostics.md',
    [
      '---',
      'title: Diagnostic codes',
      'description: Every diagnostic code Tuimark reports, grouped by the pass that finds it.',
      'editLink: false',
      '---',
      '',
      GENERATED('`tuimark agents`'),
      '',
      '# Diagnostic codes',
      '',
      'Every problem Tuimark finds is a diagnostic with a stable code. The letter names the pass (`V` parse, `L` layout, `B` bind), and the dump lists each one under `errors` with its `severity`, `code`, message, and source position. A dump with any error-severity diagnostic has `"ok": false`, and the CLI exits 2. Link to a code with its anchor, like [`/reference/diagnostics#v003`](#v003).',
      '',
      ...body,
    ].join('\n'),
  )
}

