/** Every file this script owns, path (relative to docs/) → content. */
const files = new Map()
const emit = (path, content) => {
  if (files.has(path)) throw new Error(`generate: ${path} written twice`)
  files.set(path, content.endsWith('\n') ? content : content + '\n')
}

function tuimark(args, { cwd = REPO, exit = [0] } = {}) {
  const r = spawnSync(TUIMARK, args, {
    cwd,
    encoding: 'utf8',
    maxBuffer: 64 << 20,
    env: { PATH: process.env.PATH ?? '', HOME: process.env.HOME ?? '', LANG: 'en_US.UTF-8' },
  })
  if (r.error) throw r.error
  if (!exit.includes(r.status)) {
    throw new Error(`generate: tuimark ${args.join(' ')} (in ${relative(REPO, cwd) || '.'}) exited ${r.status}, want ${exit.join(' or ')}\n${r.stderr}${r.stdout.slice(0, 2000)}`)
  }
  return { out: r.stdout, err: r.stderr, status: r.status }
}

const GENERATED = (source) =>
  `{/* Generated by docs/scripts/generate.mjs from ${source}. Do not edit by hand: run \`task docs-gen\`. */}`

/**
 * Text from `tuimark agents` as MDX: outside code spans, `{` and `}` would
 * start a JavaScript expression and `<` a JSX tag, so they are escaped.
 */
function mdx(text) {
  let out = ''
  let i = 0
  while (i < text.length) {
    if (text[i] === '`') {
      let n = 0
      while (text[i + n] === '`') n++
      const end = text.indexOf('`'.repeat(n), i + n)
      if (end < 0) throw new Error(`generate: unbalanced code span in: ${text}`)
      out += text.slice(i, end + n)
      i = end + n
      continue
    }
    const c = text[i]
    out += c === '{' || c === '}' ? `\\${c}` : c === '<' ? '&lt;' : c
    i++
  }
  return out
}

