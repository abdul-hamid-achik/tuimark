#!/usr/bin/env node
// Usage: node scripts/embed-checksums.mjs CHECKSUMS.txt VERSION
//
// Rewrites src/embedded.ts with the version and the SHA-256 of the six raw
// binaries of release VERSION, read from that release's checksums.txt. Run by
// release.yml after `npm version` and before the build, so dist/embedded.js
// (and src/embedded.ts, which Bun runs) carry the hashes. Fails if any of the
// six is missing.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const TARGETS = [
  "darwin_amd64",
  "darwin_arm64",
  "linux_amd64",
  "linux_arm64",
  "windows_amd64.exe",
  "windows_arm64.exe",
];

/** The text of src/embedded.ts for `version` and a checksums.txt. Throws when a binary is not listed. */
export function render(checksums, version) {
  const sums = new Map();
  for (const line of checksums.split(/\r?\n/)) {
    const m = /^([0-9a-fA-F]{64}) [ *]?(.+?)\s*$/.exec(line);
    if (m) sums.set(m[2], m[1].toLowerCase());
  }
  const table = {};
  for (const target of TARGETS) {
    const name = `tuimark_${version}_${target}`;
    const sum = sums.get(name);
    if (sum === undefined) throw new Error(`checksums.txt does not list ${name}`);
    table[name] = sum;
  }
  return `// Generated by scripts/embed-checksums.mjs from the checksums.txt of release v${version}. Do not edit or commit.

export interface Embedded {
  version: string;
  sha256: Record<string, string>;
}

export const embedded: Embedded | undefined = ${JSON.stringify({ version, sha256: table }, null, 2)};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [file, version] = process.argv.slice(2);
  if (!file || !version) {
    console.error("usage: embed-checksums.mjs CHECKSUMS.txt VERSION");
    process.exit(2);
  }
  try {
    const out = fileURLToPath(new URL("../src/embedded.ts", import.meta.url));
    writeFileSync(out, render(readFileSync(file, "utf8"), version));
    console.log(`embedded the checksums of v${version} in src/embedded.ts`);
  } catch (error) {
    console.error(`embed-checksums: ${error.message}`);
    process.exit(1);
  }
}
